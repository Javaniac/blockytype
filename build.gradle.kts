/**
 * Writes `libraries.txt`: every runtime library (Kotlin included) as `group:artifact:version[:classifier] sha256`.
 * The jar carries only this list, `com.javaniac.blockytype.bootstrap.Bootstrap` downloads the libraries on first start.
 */
val generateLibraries by tasks.registering {
    val artifacts = configurations.runtimeClasspath.get().incoming.artifacts.resolvedArtifacts
    val out = layout.buildDirectory.file("generated/libraries/libraries.txt")
    outputs.file(out)
    doLast {
        val lines = artifacts.get().map { a ->
            val id = a.id.componentIdentifier as ModuleComponentIdentifier
            val base = "${id.module}-${id.version}"
            val name = a.file.name
            require(name.startsWith(base) && name.endsWith(".jar")) { "Unexpected library file name: $name" }
            val classifier = name.removePrefix(base).removeSuffix(".jar").removePrefix("-").ifEmpty { null }
            val sha = MessageDigest.getInstance("SHA-256").digest(a.file.readBytes()).joinToString("") { "%02x".format(it) }
            "${id.group}:${id.module}:${id.version}${classifier?.let { ":$it" } ?: ""} $sha"
        }.sorted()
        out.get().asFile.apply {
            parentFile.mkdirs()
            writeText("# Generated by Gradle (generateLibraries): runtime libraries the bootstrap downloads.\n" + lines.joinToString("\n") + "\n")
        }
    }
}

/**
 * The sound pack for the release (upload it, then pin its SHA-256 in `SoundDownloader`): `assets/sounds` as a reproducible zip.
 */
val soundsZip by tasks.registering(Zip::class) {
    from("assets/sounds")
    archiveFileName = "sounds.zip"
    destinationDirectory = layout.buildDirectory.dir("assets-release")
    isPreserveFileTimestamps = false
    isReproducibleFileOrder = true
    // Same bytes on Windows and Linux, so the pinned SHA-256 matches what CI builds.
    filePermissions { unix("rw-r--r--") }
    dirPermissions { unix("rwxr-xr-x") }
    doLast {
        val f = archiveFile.get().asFile
        println("sounds.zip sha256 " + MessageDigest.getInstance("SHA-256").digest(f.readBytes()).joinToString("") { "%02x".format(it) })
    }
}

